"""Hand-laid SVG views — the ones auto-layout gets wrong.

A user story is a walk *through* the system: who touches it, in what order, and
where it hands off. Auto-layout hides exactly that, so the story view is drawn on
an explicit grid — one lane per participant, one column per step — the way a
swimlane is drawn on a whiteboard. Nothing here is generated by a layout engine,
so the picture is stable across renders and easy to reason about.

The SVG carries its own <style>, scoped to a root class, defining both themes: it
therefore looks right inline in the explorer *and* as an exported file.
"""

from __future__ import annotations

from typing import Any, Dict, List

from _common import esc, norm_key

LANE_W = 176          # left rail holding the participant names
COL_W = 208           # one step
LANE_H = 96           # one participant row
HEAD_H = 38           # column header strip
PAD = 14

KIND_CLASS = {
    "ui": "k-ui", "service": "k-svc", "store": "k-store", "queue": "k-queue",
    "external": "k-ext", "actor": "k-actor",
}
CHANGE_CLASS = {"added": "c-add", "modified": "c-mod", "removed": "c-del", "existing": ""}


def text_width(text: str, size: float) -> float:
    """Rough advance width: CJK is square, latin is about 0.55em."""
    total = 0.0
    for ch in text:
        total += size if ord(ch) > 0x2E80 else size * 0.55
    return total


def fit_lines(text: str, width: float, size: float, max_lines: int = 3) -> List[str]:
    """Greedy wrap that works for latin words and for CJK runs alike."""
    text = " ".join(str(text or "").split())
    if not text:
        return []
    lines: List[str] = []
    line = ""
    tokens: List[str] = []
    buf = ""
    for ch in text:
        if ord(ch) > 0x2E80:            # CJK breaks anywhere
            if buf:
                tokens.append(buf)
                buf = ""
            tokens.append(ch)
        elif ch == " ":
            if buf:
                tokens.append(buf)
                buf = ""
        else:
            buf += ch
    if buf:
        tokens.append(buf)

    for tok in tokens:
        sep = "" if (not line or ord(tok[0]) > 0x2E80 or ord(line[-1]) > 0x2E80) else " "
        candidate = line + sep + tok
        if line and text_width(candidate, size) > width:
            lines.append(line)
            line = tok
            if len(lines) == max_lines:
                break
        else:
            line = candidate
    if line and len(lines) < max_lines:
        lines.append(line)
    if len(lines) == max_lines and (text_width(" ".join(lines), size) < text_width(text, size) - 1):
        last = lines[-1]
        while last and text_width(last + "…", size) > width:
            last = last[:-1]
        lines[-1] = last.rstrip() + "…"
    return lines


def _tspans(lines: List[str], x: float, y: float, size: float, cls: str = "") -> str:
    out = []
    for i, line in enumerate(lines):
        out.append(f'<tspan x="{x:.0f}" y="{y + i * (size + 3):.0f}">{esc(line, 200)}</tspan>')
    klass = f' class="{cls}"' if cls else ""
    return f'<text{klass}>' + "".join(out) + "</text>"


