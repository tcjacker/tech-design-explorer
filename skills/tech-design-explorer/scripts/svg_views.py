def swimlane(steps: List[Dict[str, Any]], *, uid: str, lanes_meta: Dict[str, Dict[str, str]],
             col_label: str = "Step") -> str:
    """One story, drawn as lanes × steps.

    `steps` is a list of {component, action, outcome, kind, change}; every step
    occupies its own column, in its participant's lane.
    """
    lanes: List[str] = []
    for st in steps:
        name = st.get("component") or "—"
        if name not in lanes:
            lanes.append(name)
    cols = len(steps)
    width = LANE_W + max(1, cols) * COL_W + PAD
    height = HEAD_H + len(lanes) * LANE_H + PAD

    parts: List[str] = [
        f'<svg class="tde-swim" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}" role="img">',
        f"<style>{STYLE}</style>",
        f'<defs><marker id="ar-{uid}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" '
        f'markerHeight="7" orient="auto-start-reverse">'
        f'<path d="M0,0 L10,5 L0,10 z" fill="#8794aa"/></marker></defs>',
    ]

    # lane bands + the name rail
    for i, lane in enumerate(lanes):
        y = HEAD_H + i * LANE_H
        alt = " alt" if i % 2 else ""
        parts.append(f'<rect class="lane-band{alt}" x="0" y="{y}" width="{width}" '
                     f'height="{LANE_H}" rx="10"/>')
        meta = lanes_meta.get(norm_key(lane), {})
        parts.append(f'<rect class="rail" x="{PAD / 2:.0f}" y="{y + 10}" width="{LANE_W - PAD}" '
                     f'height="{LANE_H - 20}" rx="9"/>')
        name_lines = fit_lines(lane, LANE_W - 40, 13, 2)
        parts.append(_tspans(name_lines, PAD, y + 34, 13, "lane-name"))
        role = meta.get("role") or meta.get("responsibility") or ""
        if role:
            parts.append(_tspans(fit_lines(role, LANE_W - 40, 11, 1), PAD,
                                 y + 34 + len(name_lines) * 16, 11, "lane-role"))

    # column headers
    for i, st in enumerate(steps):
        x = LANE_W + i * COL_W + 12
        label = st.get("phase") or f"{col_label} {i + 1}"
        parts.append(_tspans([label.upper()], x, 24, 11, "col-head"))

    # connectors first so cards sit on top of them
    def cell(i: int):
        lane_i = lanes.index(steps[i].get("component") or "—")
        x = LANE_W + i * COL_W + 12
        y = HEAD_H + lane_i * LANE_H + 18
        return x, y, COL_W - 24, LANE_H - 36

    for i in range(len(steps) - 1):
        x1, y1, w1, h1 = cell(i)
        x2, y2, _, h2 = cell(i + 1)
        sx, sy = x1 + w1, y1 + h1 / 2
        ex, ey = x2, y2 + h2 / 2
        mid = (sx + ex) / 2
        if abs(sy - ey) < 1:
            d = f"M{sx:.0f},{sy:.0f} L{ex - 4:.0f},{ey:.0f}"
        else:
            d = (f"M{sx:.0f},{sy:.0f} L{mid:.0f},{sy:.0f} "
                 f"Q{mid + 8:.0f},{sy:.0f} {mid + 8:.0f},{sy + (8 if ey > sy else -8):.0f} "
                 f"L{mid + 8:.0f},{ey - (8 if ey > sy else -8):.0f} "
                 f"Q{mid + 8:.0f},{ey:.0f} {mid + 16:.0f},{ey:.0f} L{ex - 4:.0f},{ey:.0f}")
        parts.append(f'<path class="link" data-step="{i + 1}" d="{d}" '
                     f'marker-end="url(#ar-{uid})"/>')

    # the step cards
    for i, st in enumerate(steps):
        x, y, w, h = cell(i)
        meta = lanes_meta.get(norm_key(st.get("component") or ""), {})
        klass = " ".join(filter(None, [
            "swim-step",
            KIND_CLASS.get(meta.get("kind", "external"), "k-ext"),
            CHANGE_CLASS.get(st.get("change") or meta.get("change") or "existing", ""),
        ]))
        parts.append(f'<g class="{klass}" data-step="{i}">')
        parts.append(f'<rect class="card" x="{x}" y="{y}" width="{w}" height="{h}" rx="10"/>')
        title = fit_lines(st.get("action") or "", w - 24, 12.5, 2)
        parts.append(_tspans(title, x + 12, y + 26, 12.5, "card-title"))
        note = st.get("outcome") or ""
        if note:
            parts.append(_tspans(fit_lines(note, w - 24, 11, 2), x + 12,
                                 y + 26 + len(title) * 16, 11, "card-note"))
        marker = {"added": "+", "modified": "~", "removed": "−"}.get(st.get("change") or "")
        if marker:
            # bottom-right, clear of the title's own text box
            parts.append(f'<text class="chip" x="{x + w - 12}" y="{y + h - 9}" '
                         f'text-anchor="end">{marker}</text>')
        parts.append("</g>")

    parts.append("</svg>")
    return "".join(parts)
